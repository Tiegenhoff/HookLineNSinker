// Creates a namespace so the Fish Enum belongs to the same project code organization as the casting function
namespace HookLineNSinker
{
    // Defines the identifiable types of fish used by the project
    public enum Fish
    {
        // Represents an empty or unassigned fish entry
        None = 0,

        // Identifies a Yellowfish (just as an example, we can change this and the following names later)
        YELLOWFISH = 1,

        // Identifies a Bass
        BASS = 2,

        // Identifies a Salmon
        SALMON = 3,

        // Identifies a Tuna
        TUNA = 4,

        // Identifies a Trout
        TROUT = 5
    }
}
